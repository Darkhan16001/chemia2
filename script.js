function toggleStudent(id) {
  const s = getStudent(id);
  if (!s) return;

  if (s.present && state.marks.some(m=>m.id===id)) {
    alert("Бұл оқушы бағаланған. Оның бағасы журналда сақталған.");
    return;
  }

  s.present = !s.present;
  state.teams = [[],[],[]];
  state.oralScores = [0,0,0];
  state.oralIndex = 0;
  state.oralOpen = false;

  if (!s.present && state.selectedStudent === id) {
    state.selectedStudent = null;
    state.selectedProblem = null;
    state.answerOpen = false;
  }

  save();
  showSlide();
}

