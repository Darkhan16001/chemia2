function safeArithmetic(source) {
  if (!/^[0-9+\-*/(). ]+$/.test(source)) throw Error();

  let pos=0;

  function spaces() {
    while (source[pos]===" ") pos++;
  }

  function factor() {
    spaces();

    if (source[pos]==="+") {
      pos++;
      return factor();
    }

    if (source[pos]==="-") {
      pos++;
      return -factor();
    }

    if (source[pos]==="(") {
      pos++;
      const n=expression();
      spaces();
      if (source[pos]!==")") throw Error();
      pos++;
      return n;
    }

    const match=
      /^(?:\d+(?:\.\d*)?|\.\d+)/.exec(source.slice(pos));

    if (!match) throw Error();

    pos+=match[0].length;
    return Number(match[0]);
  }

  function term() {
    let n=factor();

    while (true) {
      spaces();
      const op=source[pos];
      if (op!=="*" && op!=="/") break;

      pos++;
      const b=factor();
      n=op==="*" ? n*b : n/b;
    }

    return n;
  }

  function expression() {
    let n=term();

    while (true) {
      spaces();
      const op=source[pos];
      if (op!=="+" && op!=="-") break;

      pos++;
      const b=term();
      n=op==="+" ? n+b : n-b;
    }

    return n;
  }

  const result=expression();
  spaces();

  if (pos!==source.length || !Number.isFinite(result)) {
    throw Error();
  }

  return Number(result.toPrecision(12));
}

