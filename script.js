function chooseStudent() {
  if (state.selectedStudent !== null) return;

  const available = presentStudents().filter(s =>
    !state.marks.some(m=>m.id===s.id)
  );

  if (!available.length) {
    alert("Барлық қатысушы бағаланды.");
    return;
  }

  const chosen = available[random(available.length)];

  let tasks = problems
    .map((_,i)=>i)
    .filter(i=>!state.usedProblems.includes(i));

  if (!tasks.length) {
    state.usedProblems = [];
    tasks = problems.map((_,i)=>i);
  }

  const taskIndex = tasks[random(tasks.length)];

  state.selectedStudent = chosen.id;
  state.selectedProblem = taskIndex;
  state.answerOpen = false;
  state.usedProblems.push(taskIndex);

  save();
  showSlide();
}

function revealIndividual() {
  if (state.selectedStudent === null) return;

  state.answerOpen = true;
  save();
  showSlide();
}

function giveGrade(grade) {
  if (
    state.selectedStudent === null ||
    !state.answerOpen
  ) return;

  const s = getStudent(state.selectedStudent);
  const problem = problems[state.selectedProblem];

  if (!s || !problem) return;

  state.marks.push({
    id:s.id,
    name:s.name,
    team:teamOf(s.id),
    question:problem[0],
    answer:problem[1],
    grade
  });

  state.selectedStudent = null;
  state.selectedProblem = null;
  state.answerOpen = false;

  save();
  showSlide();
}

