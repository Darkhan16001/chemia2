const STORAGE = "darkhan_reaction_rate_v1";

function initialState() {
  return {
    students:names.map((name,i) => ({
      id:i+1,name,present:true
    })),
    teams:[[],[],[]],
    marks:[],
    selectedStudent:null,
    selectedProblem:null,
    answerOpen:false,
    usedProblems:[],
    oralIndex:0,
    oralOpen:false,
    oralScores:[0,0,0],
    notebookOpen:{}
  };
}

let state = initialState();

try {
  const saved = JSON.parse(localStorage.getItem(STORAGE));

  if (
    saved &&
    Array.isArray(saved.students) &&
    Array.isArray(saved.teams) &&
    Array.isArray(saved.marks)
  ) {
    state = {...initialState(),...saved};
  }
} catch (e) {
  console.warn("Сақтау деректері оқылмады:",e);
}

function save() {
  try {
    localStorage.setItem(STORAGE,JSON.stringify(state));
  } catch (e) {
    console.warn("Сақтау мүмкін болмады:",e);
  }
}

function presentStudents() {
  return state.students.filter(s => s.present);
}

function getStudent(id) {
  return state.students.find(s => s.id === id);
}

function teamOf(id) {
  const i = state.teams.findIndex(t => t.includes(id));
  return i < 0 ? null : i + 1;
}

