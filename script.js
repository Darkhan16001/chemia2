function distributeTeams() {
  const ids = shuffle(
    presentStudents().map(s=>s.id)
  );

  if (!ids.length) {
    alert("Қатысушыларды белгіле.");
    return;
  }

  if (state.marks.length) {
    if (!confirm("Топтарды қайта бөлесіз бе? Жеке бағалар сақталады, топтық ойын қайта басталады.")) {
      return;
    }
  }

  state.teams = [[],[],[]];

  ids.forEach((id,i)=>{
    state.teams[i%3].push(id);
  });

  state.oralScores = [0,0,0];
  state.oralIndex = 0;
  state.oralOpen = false;

  save();
  showSlide();
}

