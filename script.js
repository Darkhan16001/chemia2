function particles(hot=false,count=9) {
  return `
    <div class="diagram">
      <div class="particle-row">
        ${Array.from({length:count},() => `
          <div class="particle ${hot?"hot":""}"></div>
        `).join("")}
      </div>
      <p class="small center">
        ${hot
          ? "Жоғары температура: бөлшектер тезірек қозғалады"
          : "Төмен температура: бөлшектер баяуырақ қозғалады"}
      </p>
    </div>
  `;
}

function factorCards(items) {
  return `
    <div class="grid2">
      ${items.map(x => `
        <div class="card">
          <h3>${x[0]}</h3>
          <p>${x[1]}</p>
        </div>
      `).join("")}
    </div>
  `;
}

